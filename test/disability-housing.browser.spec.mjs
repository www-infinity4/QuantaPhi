import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const origin='http://127.0.0.1:8799';
const url=origin+'/disability-housing.html';
test.use({viewport:{width:390,height:844}});
test('phone intake: validate, prepare, download, recover and erase without sending answers',async({page})=>{
 const outbound=[];page.on('request',r=>{if(!r.url().startsWith(origin)&&!r.url().startsWith('blob:'))outbound.push(r.url());});
 await page.goto(url);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await expect(page.getByText('Choose the state or territory where you want housing.')).toBeVisible();
 await page.locator('#haState').selectOption('IA');await page.locator('#haCity').fill('Lovilia');
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.locator('#haNext').click();await expect(page.locator('#haIncome')).toHaveAttribute('aria-invalid','true');
 await page.locator('#haBenefits').selectOption('ssdi');await page.locator('#haAge').selectOption('18-61');
 await page.locator('#haIncome').fill('1234');await page.getByText('Add a name and budget details',{exact:false}).click();
 await page.locator('#haName').fill('<script>test-only</script>');await page.locator('#haTarget').fill('100');
 await page.locator('#haRemember').check();await page.locator('#haNext').click();
 await expect(page.getByRole('heading',{name:'USDA Section 502 Direct',exact:true})).toBeVisible();
 await expect(page.locator('#haResultFacts')).toContainText('$1,234.00 / month');
 await expect(page.getByRole('link',{name:'Official USDA application',exact:false})).toHaveAttribute('href',/forms.sc.egov.usda.gov/);
 const downloadPromise=page.waitForEvent('download');await page.locator('#haDownload').click();const download=await downloadPromise;
 const content=await readFile(await download.path(),'utf8');
 expect(content).toContain('Lovilia');expect(content).toContain('$14,808.00');expect(content).toContain('$100.00');
 expect(content).toContain('<script>test-only</script>');expect(content).toContain('Not an official application');
 expect(outbound).toEqual([]);
 await page.reload();await expect(page.locator('#haRestore')).toBeVisible();await expect(page.locator('#haCity')).toHaveValue('Lovilia');
 await page.locator('#haNext').click();await expect(page.locator('#haIncome')).toHaveValue('1234');
 await page.locator('#haRemember').uncheck();expect(await page.evaluate(()=>localStorage.getItem('quantaphi:housing:saved:v1'))).toBeNull();
 await page.locator('#haClear').click();await page.locator('#haCancelClear').click();await expect(page.locator('#haIncome')).toHaveValue('1234');
 await page.locator('#haClear').click();await page.locator('#haConfirmClear').click();
 expect(await page.evaluate(()=>sessionStorage.getItem('quantaphi:housing:tab:v1'))).toBeNull();
 await page.reload();await expect(page.locator('#haRestore')).toBeHidden();await expect(page.locator('#haCity')).toHaveValue('');
});
test('repair grants and rental handoffs respond to the visitor instead of guaranteeing housing',async({page})=>{
 await page.goto(url+'?goal=repair&state=IA');await page.locator('#haOwns').selectOption('no');
 await page.locator('#haNext').click();await page.locator('#haAge').selectOption('18-61');await page.locator('#haIncomeUnknown').check();
 await page.locator('#haNext').click();await expect(page.locator('[data-program="504"]')).toContainText('Disability alone does not remove');
 await expect(page.locator('#haTasks')).toContainText('renter cannot use it to buy');
 await page.locator('#haEdit').click();await page.getByLabel('Find a rental',{exact:false}).check();
 await page.locator('#haState').selectOption('CA');await page.locator('#haNext').click();await page.locator('#haNext').click();
 await expect(page.locator('[data-program="rental"]')).toBeVisible();await expect(page.locator('#haContact')).toContainText('local housing agency');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
