import {test,expect} from '@playwright/test';
test.use({viewport:{width:390,height:844}});
const base='http://127.0.0.1:8799';
test('Infinity Brands offers voluntary support without charging or promising ranking',async({page})=>{
 await page.goto(base+'/infinity-affiliates.html',{waitUntil:'domcontentloaded'});
 const program=page.locator('#infinityAffiliatesStandalone #iaAdvertisingProgram');
 await expect(program.getByRole('heading',{name:'Support helpful advertising'})).toBeVisible({timeout:20000});
 await expect(program.getByText('Voluntary contribution',{exact:true})).toBeVisible();
 await expect(program.getByText('$100 · 30-day performance review',{exact:true})).toBeVisible();
 await expect(program.locator('#iaUnderTarget')).toBeHidden();
 await program.locator('input[name=businessName]').fill('Example Shoe Company');
 await program.locator('input[name=siteUrl]').fill('https://example-shoe.org');
 await program.locator('input[name=acknowledge]').check();
 await program.getByRole('button',{name:'Prepare review request'}).click();
 await expect(program.locator('#iaAdPrepared')).toBeVisible();
 const u=new URL(await program.locator('#iaAdReviewLink').getAttribute('href'));
 expect(u.hostname).toBe('github.com');
 expect(u.searchParams.get('body')).toContain('No mandatory amount');
 expect(u.searchParams.get('body')).toContain('NOT a purchase, billing authorization, or sales guarantee');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3)).toBeTruthy();
});
test('performance request explicitly requires consent to proposed below-target $100 fee',async({page})=>{
 await page.goto(base+'/infinity-affiliates.html',{waitUntil:'domcontentloaded'});
 const program=page.locator('#infinityAffiliatesStandalone #iaAdvertisingProgram');
 await program.locator('input[value=performance-review]').check();
 await expect(program.locator('#iaUnderTarget')).toBeVisible();
 await program.locator('input[name=businessName]').fill('Example Shoe Company');
 await program.locator('input[name=siteUrl]').fill('https://example-shoe.org');
 await program.locator('input[name=acknowledge]').check();
 await program.getByRole('button',{name:'Prepare review request'}).click();
 await expect(program.locator('#iaAdPrepared')).toBeHidden();
 await expect(program.locator('.ia-advertiser-feedback')).toContainText(/Acknowledge the exact proposed/);
 await program.locator('input[name=underTargetFeeAcknowledged]').check();
 await program.getByRole('button',{name:'Prepare review request'}).click();
 await expect(program.locator('#iaAdPrepared')).toBeVisible();
 const u=new URL(await program.locator('#iaAdReviewLink').getAttribute('href'));
 expect(u.searchParams.get('body')).toContain('Proposed $100 fee only if verified 30-day');
 expect(u.searchParams.get('body')).toContain('NOT a purchase, billing authorization, or sales guarantee');
});
