'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const service=require('../phone/quickdial.js');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
test('Infinity service calls route only to explicit first-party destinations',()=>{
 assert.equal(service.entries.length,6);
 assert.deepEqual(service.entries.map(x=>x.code),['*100','*101','*102','*103','*104','*105']);
 assert.equal(service.resolve('*100')?.url,'/');
 assert.equal(service.resolve('4-333-3333#')?.url,'/');
 assert.equal(service.resolve('4 333 3333 #')?.url,'/');
 assert.equal(service.resolve('4-333-3333')?.url,undefined);
 assert.equal(service.resolve('*101')?.url,'/platinum/');
 assert.equal(service.resolve('*102')?.url,'/#bubblesAICard');
 assert.equal(service.resolve('*103')?.url,'/#robotBrainOwner');
 assert.equal(service.resolve('*104')?.url,'/cellular/');
 assert.equal(service.resolve('*105')?.url,'/phone/');
 assert.equal(service.resolve('robot')?.code,'*103');
 assert.equal(service.resolve('quanta')?.code,'*100');
 assert.equal(service.resolve('100'),null);
 assert.equal(service.resolve('911'),null);
 assert.equal(service.resolve('1234567890'),null);
 assert.equal(service.resolve('+14155552671'),null);
 assert.equal(service.resolve('https://evil.example'),null);
 assert.equal(service.resolve('*999'),null);
 assert.equal(service.internalPath({code:'*100',url:'//attacker'}),null);
 for(const entry of service.entries)assert.match(entry.url,/^\/(?!\/)/);
});
test('The dialer uses the same web identity and does not confuse it with an LTE SIM key',()=>{
 const js=read('phone/phone.js'),html=read('phone/index.html'),quick=read('phone/quickdial.js');
 assert.match(js,/quickDial\?\.resolve\(\$\('dial'\)\.value\)/);
 assert.match(js,/renderQuickDial\(\)/);
 assert.match(js,/\$\('web-key-status'\)\.textContent=me/);
 assert.match(html,/id="web-key-status"/);
 assert.match(html,/id="sim-key-status"/);
 assert.match(html,/quickdial-grid/);
 assert.match(html,/phone\/quickdial\.js/);
 assert.match(html,/phone\/phone\.js/);
 assert.match(quick,/not assigned telephone numbers/i);
 assert.doesNotMatch(quick,/fetch\(|XMLHttpRequest|sendBeacon|document\.cookie/);
 assert.doesNotMatch(js,/sim-key-status'\)\.textContent\s*=\s*['"]connected/i);
});

test('Infinity reachability badge checks real switchboard response, not raw LTE text',()=>{
 const html=read('phone/index.html');
 const js=read('phone/phone.js');
 assert.match(html,/id="infinity-signal"/);
 assert.match(html,/existing Internet connection/);
 assert.match(js,/health\.service!=='infinity-platinum-switchboard'/);
 assert.match(js,/renderInfinitySignal\(false\)/);
 assert.match(html,/4-333-3333#/);
});
