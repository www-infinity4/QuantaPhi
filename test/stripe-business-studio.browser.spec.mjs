import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';

const base='http://127.0.0.1:8799';
test.use({viewport:{width:360,height:780}});
test('Stripe business studio builds 500 local drafts with no Stripe account or bank form',async({page})=>{
 const outbound=[];
 page.on('request',r=>{if(r.method()==='POST')outbound.push(r.url());});
 await page.goto(base+'/stripe-business-studio.html',{waitUntil:'domcontentloaded'});
 await expect(page.getByRole('heading',{name:'Stripe Business Studio'})).toBeVisible();
 await expect(page.getByText('Stripe not connected to this seller.')).toBeVisible();
 await expect(page.locator('#stripeExport')).toBeDisabled();
 await page.locator('#stripeSellerSlug').fill('fred-coins');
 await page.locator('#stripeDisplayName').fill('Fred Coin Finds');
 await page.locator('#stripeBusinessType').selectOption('coins');
 await page.locator('#stripePrice').fill('25.00');
 await page.locator('#stripeSellerNotes').fill('Vintage coins and verified grading details');
 await page.locator('#stripeSellerCards').fill(Array.from({length:500},(_,i)=>'coin-'+(i+1)).join('\n'));
 await page.locator('#stripeDraft').click();
 await expect(page.locator('#stripeStatus')).toContainText('500 Stripe seller Quick Card drafts prepared');
 await expect(page.locator('#stripeExport')).toBeEnabled();
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#stripeExport').click()]);
 const saved=JSON.parse(readFileSync(await download.path(),'utf8'));
 expect(saved.cardCount).toBe(500);
 expect(saved.cards[0].sellerSlug).toBe('fred-coins');
 expect(saved.cards[499].priceCents).toBe(2500);
 expect(saved.accountStatus).toBe('not_connected');
 expect(saved.checkoutEnabled).toBe(false);
 expect(saved.cards.every(x=>x.checkoutEnabled===false)).toBe(true);
 expect(saved.cashWalletLinking).toBe('not_connected');
 expect(outbound).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)).toBeLessThanOrEqual(4);
});
test('Lawn service and changed price invalidate stale export, never claim a bank balance',async({page})=>{
 await page.goto(base+'/stripe-business-studio.html',{waitUntil:'domcontentloaded'});
 await page.locator('#stripeSellerSlug').fill('fred-lawns');
 await page.locator('#stripeDisplayName').fill('Fred Lawn Care');
 await page.locator('#stripeBusinessType').selectOption('services');
 await page.locator('#stripePrice').fill('50.00');
 await page.locator('#stripeSellerCards').fill('lawn-spring\nlawn-weekly');
 await page.locator('#stripeDraft').click();
 await expect(page.locator('#stripeExport')).toBeEnabled();
 await page.locator('#stripePrice').fill('60.00');
 await expect(page.locator('#stripeExport')).toBeDisabled();
 await page.locator('#stripeDraft').click();
 await expect(page.locator('#stripePreview')).toContainText('6000');
 await page.locator('#stripeSellerCards').fill('lawn-spring\nlawn-spring');
 await page.locator('#stripeDraft').click();
 await expect(page.locator('#stripeStatus')).toContainText('duplicate_card');
 await expect(page.locator('#stripeExport')).toBeDisabled();
 await page.locator('#stripeClear').click();
 await expect(page.locator('#stripeSellerCards')).toHaveValue('');
 await expect(page.getByText('No guaranteed cash returns.')).toBeVisible();
 await expect(page.locator('input[type="file"]')).toHaveCount(0);
});

test('new business without cards can still prepare an honest nonnegative draft',async({page})=>{
 await page.goto(base+'/stripe-business-studio.html',{waitUntil:'domcontentloaded'});
 await page.locator('#stripeSellerSlug').fill('new-lawn');
 await page.locator('#stripeDisplayName').fill('New Lawn Service');
 await page.locator('#stripeBusinessType').selectOption('services');
 await page.locator('#stripePrice').fill('30.00');
 await page.locator('#stripeDraft').click();
 await expect(page.locator('#stripeStatus')).toContainText('0 Stripe seller Quick Card drafts');
 await expect(page.locator('#stripePreview')).toContainText('"unlistedRemaining": 0');
 await expect(page.locator('#stripeExport')).toBeEnabled();
});
