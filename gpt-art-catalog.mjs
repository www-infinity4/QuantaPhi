export function normalizeArtCard(card){
 if(!card||!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(card.id||'')||
  !['gpt-art','fantasy'].includes(card.collection)||typeof card.title!=='string'||card.title.length<3||card.title.length>100||
  card.isSponsored!==false||!/^\/assets\/gpt-art\/[a-z0-9-]+\.webp$/.test(card.imagePath||''))return null;
 return card;
}
export function eligibleArtCards(cards=GPT_ART_CARDS){
 if(!Array.isArray(cards))return [];
 return cards.map(normalizeArtCard).filter(card=>card&&card.ready===true&&card.rights==='reviewed');
}
