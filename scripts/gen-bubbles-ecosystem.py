import json, re, subprocess, sys, datetime
from concurrent.futures import ThreadPoolExecutor
from itertools import count
def gh(*a):
    try:
        r = subprocess.run(["gh", *a], capture_output=True, text=True, timeout=40)
    except Exception:
        return ""
    return r.stdout if r.returncode == 0 else ""
def blurb(md):
    keep = []
    for l in md.splitlines():
        l = l.strip()
        if not l or l[0] in "#![|<>-=`" or l.startswith("[!["):
            continue
        keep.append(re.sub(r"[*_`\[\]]", "", l))
        if sum(map(len, keep)) > 200:
            break
    return " ".join(keep)[:220]
OWNERS = ["www-infinity4"]
tick = count(1)
def one(job):
    o, r, total = job
    n = r["name"]
    meta = gh("api", f"repos/{o}/{n}", "--jq",
              '[.has_pages, (.homepage // "")] | @tsv').strip().split("\t")
    pages = bool(meta and meta[0] == "true")
    home = meta[1] if len(meta) > 1 else ""
    live = home or (f"https://{o}.github.io/{n}/" if pages else "")
    rd = gh("api", f"repos/{o}/{n}/readme", "-H", "Accept: application/vnd.github.raw")
    k = next(tick)
    if k % 20 == 0 or k == total:
        print(f"  ...{k}/{total}", file=sys.stderr, flush=True)
    return {"owner": o, "name": n, "desc": r.get("description") or "",
            "blurb": blurb(rd),
            "lang": (r.get("primaryLanguage") or {}).get("name", ""),
            "live": live, "fork": bool(r.get("isFork")),
            "updated": (r.get("updatedAt") or "")[:10]}
jobs = []
for o in OWNERS:
    raw = gh("repo", "list", o, "--limit", "400", "--json",
             "name,description,primaryLanguage,updatedAt,isPrivate,isArchived,isFork")
    if not raw:
        print("skip", o); continue
    rows = [r for r in json.loads(raw) if not r["isPrivate"] and not r["isArchived"]]
    jobs += [(o, r, len(rows)) for r in rows]
print("PUBLIC REPOS:", len(jobs), flush=True)
with ThreadPoolExecutor(6) as ex:
    out = list(ex.map(one, jobs))
out.sort(key=lambda x: x["updated"], reverse=True)
js = ("// Generated by scripts/gen-bubbles-ecosystem.py. Public repositories only. Do not hand-edit.\n"
      "export const GENERATED='" + datetime.date.today().isoformat() + "';\n"
      "export default " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
open("workers/bubbles-tools/ecosystem-data.mjs", "w", encoding="utf-8").write(js)
print("TOTAL", len(out), "BYTES", len(js.encode()))
