/* Independent StarMaker discovery controls for the universal Infinity Quick Card.
 * The only catalog records shown as song links are verified public URLs in
 * studio/songbook.mjs. No provider API, credentials, copyrighted media or
 * microphone access is inferred from browsing/listening data.
 */
import {STUDIO_SONGS,findSongs,OFFICIAL_SONGBOOK} from './studio/songbook.mjs';

const norm=value=>String(value??'').normalize('NFKD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim().replace(/\s+/g,' ');
const stop=new Set(['the','and','you','your','with','from','have','this','that','feat','song','music']);
const tokens=s=>norm(s).split(' ').filter(x=>x.length>2&&!stop.has(x));
const text=(tag,value,cls='')=>{const n=document.createElement(tag);if(cls)n.className=cls;n.textContent=value;return n;};
const official=(label,href,cls='qcx-link')=>{const a=text('a',label,cls);a.href=href;a.target='_blank';a.rel='noopener noreferrer';return a;};

/* These listening records are generated by Infinity Radio's Music Quant ledger,
 * not by StarMaker. Keep consent ephemeral and the data in the current browser.
 */
export function listeningSongs(records=[]){
 if(!Array.isArray(records))return [];
 const seen=new Set(),items=[];
 for(const record of [...records].reverse()){
  if(record?.kind!=='listening'||record.transferredAt||typeof record.song!=='string')continue;
  const song=record.song.trim().replace(/\s+/g,' ').slice(0,160);
  if(song.length<2)continue;
  const id=String(record.id||'').slice(0,110);
  if(id&&seen.has(id))continue;
  if(id)seen.add(id);
  items.push({song,createdAt:String(record.createdAt||record.startedAt||'')});
 }
 return items.slice(0,500);
}
export function rankForSinging(catalog=STUDIO_SONGS,listens=[]){
 const heard=listens.map(x=>norm(typeof x==='string'?x:x?.song)).filter(Boolean);
 return [...catalog].map((song,index)=>{
  const title=norm(song.title),artist=norm(song.artist),words=tokens(song.title);
  let score=0;
  for(const phrase of heard){
   if(phrase===title||phrase.startsWith(title+' ')||phrase.endsWith(' '+title))score+=12;
   else if(title.length>=5&&phrase.includes(title))score+=8;
   if(artist.length>3&&phrase.includes(artist))score+=5;
   const matching=words.filter(word=>phrase.split(' ').includes(word)).length;
   if(matching>=2)score+=3;
  }
  return {song,score,index};
 }).sort((a,b)=>b.score-a.score||a.index-b.index);
}
function availableListeningRecords(){
 let local=[];
 try{
  const parsed=JSON.parse(localStorage.getItem('musicPhi:listeningQuants:v1')||'[]');
  if(Array.isArray(parsed))local=parsed;
 }catch{/* Storage unavailable: recommendation remains manual. */}
 const cloud=globalThis.MusicQuantCloud?.state?.quants;
 const all=[...(Array.isArray(cloud)?cloud:[]),...local];
 const dedup=new Map();
 for(const r of all)if(r?.id)dedup.set(r.id,r);
 for(const r of all)if(!r?.id)dedup.set(Symbol('listening'),r);
 return listeningSongs([...dedup.values()]);
}
export function mountStarMakerQuickCard(root){
 if(!root)return;
 const panel=text('section','','qcx-tool');
 panel.append(text('p','SING · STARMAKER SONGBOOK','qcx-eyebrow'),text('h3','Find a song you might love singing'));
 const form=text('form','','qcx-search-form');
 const search=text('input','','qcx-input');search.type='search';search.maxLength=90;
 search.placeholder='Song or artist…';search.setAttribute('aria-label','Search verified StarMaker songs');
 const submit=text('button','Find songs','qcx-button');submit.type='submit';
 form.append(search,submit);panel.append(form);
 const picks=text('div','','qcx-song-picks');picks.setAttribute('aria-live','polite');
 const consent=text('label','','qcx-check');const check=document.createElement('input');check.type='checkbox';
 check.setAttribute('aria-label','Use my Music Quant listening history for singing suggestions');
 consent.append(check,text('span','Suggest songs from my Music Quants (optional)'));
 const status=text('p','Recommendations off. Listening history stays private.','qcx-note');
 let listens=[],expanded=false;
 function render(){
  const query=search.value.trim();
  const matches=findSongs(query);
  const ranked=rankForSinging(matches,listens);
  const personalized=check.checked&&ranked.some(x=>x.score>0);
  picks.replaceChildren();
  const max=expanded?8:3;
  for(const {song,score} of ranked.slice(0,max)){
   const item=text('div','','qcx-result');
   const body=text('div','');
   body.append(text('strong',song.title),text('p',song.artist,'qcx-note'));
   if(personalized&&score>0)body.append(text('small','Matches your Music Quant listening'));
   item.append(body,official('Sing ↗',song.url,'qcx-button'));picks.append(item);
  }
  if(!ranked.length)picks.append(text('p','No match in this small verified list. Use the full official songbook.','qcx-note'));
  more.hidden=ranked.length<=3;more.textContent=expanded?'Show fewer songs':'Show all '+ranked.length+' curated songs';
  if(!query)status.textContent=check.checked
   ?(listens.length?(personalized?'Music Quant match found · '+listens.length+' listening records available.':'No direct matches in the curated list · '+listens.length+' listening records available.'):'No listening-song records available to this card. Browse or search manually.')
   :'Recommendations off. Listening history stays private.';
  else status.textContent='Showing '+ranked.length+' verified public song links'+(check.checked?' with Music Quant suggestions':'')+'.';
 }
 const more=text('button','Show more songs','qcx-button');more.type='button';more.addEventListener('click',()=>{expanded=!expanded;render();});
 form.addEventListener('submit',e=>{e.preventDefault();expanded=true;render();});
 search.addEventListener('input',()=>{expanded=false;render();});
 check.addEventListener('change',()=>{
  listens=check.checked?availableListeningRecords():[];
  expanded=false;render();
 });
 panel.append(consent,status,picks,more);
 const actions=text('div','','qcx-controls');
 const studio=official('Record my voice ↗','/studio/#studio');
 studio.target='_self';actions.append(studio,official('Full StarMaker songbook ↗',OFFICIAL_SONGBOOK));
 panel.append(actions);
 panel.append(text('p','Verified song links only. StarMaker handles licensed karaoke, duets, effects, account sign-in and party rooms. The QuantaPhi recorder is separate. No listening history is transmitted to StarMaker.','qcx-note'));
 root.append(panel);render();
}
